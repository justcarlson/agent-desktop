#!/usr/bin/env bash
#
# Moves the Hyprland Wayland work in crates/linux under one `hyprland` module,
# shaped like the KWin backend's `input/wayland/kwin/`, and rewrites every path
# that names a moved file. The placement lives in hyprland-module.rules; the
# engine is hyprland_module.py.

set -euo pipefail

usage() {
    cat <<'EOF'
Usage: scripts/path/hyprland-module.sh [--check] [--base REV] [--rules FILE]

Moves the Wayland files the rules name under crates/linux/src/system/wayland/hyprland/
and rewrites the `mod` declarations, `use` and expression paths, `#[path]` attributes
and visibilities that the move touches, then formats the touched files with rustfmt.
A second run changes nothing. A file the Wayland work adds that no rule places
stops the run with its name.

  --check       print what would move; exit 1 if anything would, 0 if nothing
  --base REV    the commit the Wayland work branches from
                (default: merge-base of HEAD with origin/main, then main)
  --rules FILE  placement rules (default: scripts/path/hyprland-module.rules)

Rerun after each change to the Wayland branch:

  git checkout --detach <new W SHA>
  git cherry-pick <commit A>                  # adds this script and its rules
  scripts/path/hyprland-module.sh
  git add -A crates/linux
  git commit -m "refactor(linux): move the wayland backend under a hyprland module" \
             -m "Generated by scripts/path/hyprland-module.sh; no hand edits."

If the run names a file it cannot place, add a `module`, `children` or `keep`
line for it to the rules file, amend commit A, and run again.
EOF
}

for arg in "$@"; do
    if [ "$arg" = "-h" ] || [ "$arg" = "--help" ]; then
        usage
        exit 0
    fi
done

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

if ! command -v python3 >/dev/null 2>&1; then
    printf 'hyprland-module: python3 is required\n' >&2
    exit 1
fi

exec python3 -I "$repo/scripts/path/hyprland_module.py" "$repo" "$@"
